int extensionYear(const char* name) {
    size_t lo = 0, hi = sizeof kYears / sizeof kYears[0];
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        int c = strcmp(kYears[mid].name, name);
        if (c == 0) return kYears[mid].year;
        if (c < 0) lo = mid + 1;
        else hi = mid;
    }
    return 0;
}

