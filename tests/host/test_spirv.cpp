GLuint spirvShader(GLenum type, const uint32_t* words, size_t bytes, GLuint specId = 0, GLuint specVal = 0, bool spec = false) {
    GLuint s = glCreateShader(type);
    glShaderBinary(1, &s, GL_SHADER_BINARY_FORMAT_SPIR_V, words, (GLsizei)bytes);
    glSpecializeShader(s, "main", spec ? 1 : 0, &specId, &specVal);
    return s;
}

void drawQuadWith(GLuint prog) {
    const float v[] = {-1, -1, 1, -1, -1, 1, 1, 1};
    GLuint vao, vbo;
    glGenVertexArrays(1, &vao);
    glBindVertexArray(vao);
    glGenBuffers(1, &vbo);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glBufferData(GL_ARRAY_BUFFER, sizeof v, v, GL_STATIC_DRAW);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 0, nullptr);
    glEnableVertexAttribArray(0);
    glUseProgram(prog);
    glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
    glDeleteBuffers(1, &vbo);
    glDeleteVertexArrays(1, &vao);
}
