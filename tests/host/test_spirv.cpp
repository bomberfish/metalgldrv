TEST(spirv_draw_and_specialize) {
    GLint nfmt = 0, fmt = 0;
    glGetIntegerv(GL_NUM_SHADER_BINARY_FORMATS, &nfmt);
    glGetIntegerv(GL_SHADER_BINARY_FORMATS, &fmt);
    CHECK_EQ(nfmt, 1);
    CHECK_EQ(fmt, GL_SHADER_BINARY_FORMAT_SPIR_V);
    for (int pass = 0; pass < 2; pass++) {
        GLuint vs = spirvShader(GL_VERTEX_SHADER, kSpvVert, sizeof kSpvVert);
        GLuint fs = spirvShader(GL_FRAGMENT_SHADER, kSpvFrag, sizeof kSpvFrag, 7, 3, pass == 1);
        GLint st = 0;
        glGetShaderiv(vs, GL_SPIR_V_BINARY, &st);
        CHECK_EQ(st, GL_TRUE);
        glGetShaderiv(fs, GL_COMPILE_STATUS, &st);
        CHECK_EQ(st, GL_TRUE);
        GLuint p = glCreateProgram();
        glAttachShader(p, vs);
        glAttachShader(p, fs);
        glLinkProgram(p);
        glGetProgramiv(p, GL_LINK_STATUS, &st);
        CHECK_EQ(st, GL_TRUE);
        GLint maxLen = -1;
        glGetProgramiv(p, GL_ACTIVE_UNIFORM_MAX_LENGTH, &maxLen);
        CHECK_EQ(maxLen, 1);  // SPIR-V resources carry no names
        glUseProgram(p);
        glUniform1f(2, 1.0f);
        glClearColor(0, 0, 0, 0);
        glClear(GL_COLOR_BUFFER_BIT);
        drawQuadWith(p);
        CHECK_PIXEL(20, 20, 255, 128, pass == 1 ? 255 : 0, 128);
        glDeleteProgram(p);
        glDeleteShader(vs);
        glDeleteShader(fs);
    }
    CHECK_GL();
}

TEST(spirv_errors) {
    GLuint s = glCreateShader(GL_VERTEX_SHADER);
    uint32_t junk[5] = {1, 2, 3, 4, 5};
    glShaderBinary(1, &s, GL_SHADER_BINARY_FORMAT_SPIR_V, junk, sizeof junk);
    CHECK_EQ(glGetError(), GL_INVALID_VALUE);
    glShaderBinary(1, &s, 0x1234, kSpvVert, sizeof kSpvVert);
    CHECK_EQ(glGetError(), GL_INVALID_ENUM);
    glShaderBinary(1, &s, GL_SHADER_BINARY_FORMAT_SPIR_V, kSpvVert, sizeof kSpvVert);
    CHECK_EQ(glGetError(), GL_NO_ERROR);
    glCompileShader(s);
    CHECK_EQ(glGetError(), GL_INVALID_OPERATION);
    glSpecializeShader(s, "nope", 0, nullptr, nullptr);
    CHECK_EQ(glGetError(), GL_INVALID_VALUE);
    GLuint id = 99, val = 1;
    glSpecializeShader(s, "main", 1, &id, &val);
    CHECK_EQ(glGetError(), GL_INVALID_VALUE);
    GLint st = 1;
    glGetShaderiv(s, GL_COMPILE_STATUS, &st);
    CHECK_EQ(st, GL_FALSE);
    glSpecializeShader(s, "main", 0, nullptr, nullptr);
    CHECK_EQ(glGetError(), GL_NO_ERROR);
    glSpecializeShader(s, "main", 0, nullptr, nullptr);
    CHECK_EQ(glGetError(), GL_INVALID_OPERATION);
    // mixing SPIR-V and GLSL shaders fails to link
    GLuint fs = glCreateShader(GL_FRAGMENT_SHADER);
    const char* src = "#version 450\nlayout(location = 0) out vec4 o;\nvoid main() { o = vec4(1.0); }\n";
    glShaderSource(fs, 1, &src, nullptr);
    glCompileShader(fs);
    GLuint p = glCreateProgram();
    glAttachShader(p, s);
    glAttachShader(p, fs);
    glLinkProgram(p);
    glGetProgramiv(p, GL_LINK_STATUS, &st);
    CHECK_EQ(st, GL_FALSE);
    // ShaderSource turns a SPIR-V shader back into a GLSL one
    glShaderSource(s, 1, &src, nullptr);
    glGetShaderiv(s, GL_SPIR_V_BINARY, &st);
    CHECK_EQ(st, GL_FALSE);
    glDeleteProgram(p);
    glDeleteShader(s);
    glDeleteShader(fs);
    CHECK_GL();
}
