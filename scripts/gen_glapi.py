#!/usr/bin/env python3
"""Generate the GL API surface for metalgldrv from the Khronos gl.xml registry.

Outputs (into OUTDIR):
  glapi.h        - types, enums, PFN typedefs and prototypes for every command
                   in desktop GL 1.0-4.6 (compatibility) plus the extensions we
                   advertise or that apps commonly probe.
  gl_stubs.cpp   - weak default definitions of every command. A strong
                   definition anywhere in the driver overrides the stub at link.
  gl_procs.cpp   - sorted name->address table used by *GetProcAddress.
"""
import sys
import os
import re
import xml.etree.ElementTree as ET

# Extension prefixes whose commands we include in the API surface. Commands
# that we never implement simply fall through to the weak stub.
EXT_PREFIXES = ("GL_ARB_", "GL_KHR_", "GL_EXT_", "GL_NV_", "GL_AMD_", "GL_ATI_", "GL_APPLE_", "GL_INTEL_", "GL_MESA_", "GL_OVR_")


def text_of(elem):
    return "".join(elem.itertext())


def main():
    reg_path, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    root = ET.parse(reg_path).getroot()

    # --- collect commands ---------------------------------------------------
    commands = {}
    for cmd in root.find("commands"):
        proto = cmd.find("proto")
        name = proto.find("name").text
        ret = (text_of(proto)[: -len(name)]).strip()
        params = []
        for p in cmd.findall("param"):
            pname = p.find("name").text
            ptype = text_of(p)
            ptype = ptype[: ptype.rfind(pname)].strip()
            # array suffix after name (rare in gl.xml) is kept in the decl text
            params.append((ptype, pname, text_of(p).strip()))
        commands[name] = (ret, params)

    wanted_cmds = []
    wanted_enums = set()
    seen = set()

    def add_require(req):
        for c in req.findall("command"):
            n = c.get("name")
            if n not in seen:
                seen.add(n)
                wanted_cmds.append(n)
        for e in req.findall("enum"):
            wanted_enums.add(e.get("name"))

    for feat in root.findall("feature"):
        if feat.get("api") != "gl":
            continue
        for req in feat.findall("require"):
            add_require(req)

    for ext in root.find("extensions"):
        name = ext.get("name")
        supported = ext.get("supported", "")
        if "gl" not in supported.split("|") and "glcore" not in supported.split("|"):
            continue
        if not name.startswith(EXT_PREFIXES):
            continue
        for req in ext.findall("require"):
            api = req.get("api")
            if api and api != "gl":
                continue
            add_require(req)

    # --- enums --------------------------------------------------------------
    enum_vals = {}
    for group in root.findall("enums"):
        for e in group.findall("enum"):
            api = e.get("api")
            if api and api != "gl":
                continue
            enum_vals[e.get("name")] = e.get("value")

    # --- types --------------------------------------------------------------
    type_lines = []
    for t in root.find("types"):
        api = t.get("api")
        if api and api != "gl":
            continue
        name = t.get("name") or (t.find("name").text if t.find("name") is not None else None)
        if name in ("khrplatform", "GLhandleARB"):
            if name == "GLhandleARB":
                type_lines.append("#ifdef __APPLE__\ntypedef void *GLhandleARB;\n#else\ntypedef unsigned int GLhandleARB;\n#endif")
            continue
        s = text_of(t).strip()
        if s:
            type_lines.append(s)

    # --- glapi.h ------------------------------------------------------------
    h = []
    h.append("/* Generated by scripts/gen_glapi.py from registry/gl.xml. Do not edit. */")
    h.append("#ifndef MGL_GLAPI_H\n#define MGL_GLAPI_H")
    h.append("#define __gl_h_ 1\n#define __gl_glcorearb_h_ 1\n#define __glext_h_ 1\n#define __gl_glext_h_ 1")
    h.append("#include <KHR/khrplatform.h>")
    h.append("#ifndef APIENTRY\n#define APIENTRY\n#endif\n#ifndef APIENTRYP\n#define APIENTRYP APIENTRY *\n#endif")
    h.append("#ifndef GLAPI\n#define GLAPI extern __attribute__((visibility(\"default\")))\n#endif")
    h.append("#ifdef __cplusplus\nextern \"C\" {\n#endif")
    h.extend(type_lines)
    for n in sorted(wanted_enums):
        if n in enum_vals:
            h.append("#define %s %s" % (n, enum_vals[n]))
    for n in wanted_cmds:
        ret, params = commands[n]
        plist = ", ".join(p[2] for p in params) or "void"
        h.append("typedef %s (APIENTRYP PFN%sPROC)(%s);" % (ret, n.upper(), plist))
        h.append("GLAPI %s APIENTRY %s(%s);" % (ret, n, plist))
    h.append("#ifdef __cplusplus\n}\n#endif\n#endif")
    with open(os.path.join(outdir, "glapi.h"), "w") as f:
        f.write("\n".join(h) + "\n")

    # --- gl_stubs.cpp -------------------------------------------------------
    s = []
    s.append("/* Generated by scripts/gen_glapi.py. Do not edit. */")
    s.append('#include "glapi.h"')
    s.append('#include "gl/stub_report.h"')
    s.append('extern "C" {')
    for n in wanted_cmds:
        ret, params = commands[n]
        plist = ", ".join(p[2] for p in params) or "void"
        body = "mgl_report_unimplemented(\"%s\");" % n
        if ret != "void":
            body += " return (%s)0;" % ret
        s.append("__attribute__((weak, visibility(\"default\"))) %s APIENTRY %s(%s) { %s }" % (ret, n, plist, body))
    s.append("}")
    with open(os.path.join(outdir, "gl_stubs.cpp"), "w") as f:
        f.write("\n".join(s) + "\n")

    # --- gl_procs.cpp -------------------------------------------------------
    p = []
    p.append("/* Generated by scripts/gen_glapi.py. Do not edit. */")
    p.append('#include "glapi.h"')
    p.append('#include "gl/procs.h"')
    p.append("const mgl_proc_entry mgl_gl_procs[] = {")
    for n in sorted(wanted_cmds):
        p.append('  {"%s", (void (*)(void))&%s},' % (n, n))
    p.append("};")
    p.append("const unsigned mgl_gl_procs_count = %d;" % len(wanted_cmds))
    with open(os.path.join(outdir, "gl_procs.cpp"), "w") as f:
        f.write("\n".join(p) + "\n")


if __name__ == "__main__":
    main()
