#!/usr/bin/env python3
"""Embed a text file as a C++ raw string literal expression: embed.py <input> <output>
Usage in C++:  const char* s =
               #include "file.inc"
               ;"""
import sys
src, out = sys.argv[1], sys.argv[2]
data = open(src).read()
with open(out, "w") as f:
    f.write("// Generated by scripts/embed.py from %s. Do not edit.\n" % src)
    f.write('R"MGLEMBED(' + data + ')MGLEMBED"\n')
