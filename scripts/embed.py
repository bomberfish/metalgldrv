#!/usr/bin/env python3
"""Embed a text file as a C++ raw string: embed.py <input> <output> <symbol>"""
import sys
src, out, sym = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src).read()
delim = "MGLEMBED"
with open(out, "w") as f:
    f.write("// Generated by scripts/embed.py from %s. Do not edit.\n" % src)
    # MSVC-style length limits don't apply to clang; one raw literal is fine.
    f.write('static const char %s[] = R"%s(' % (sym, delim))
    f.write(data)
    f.write(')%s";\n' % delim)
